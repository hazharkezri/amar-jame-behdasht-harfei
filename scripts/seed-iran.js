let addedUni = 0;
for (const u of UNIVERSITIES) {
  addedUni += +db.prepare("INSERT OR IGNORE INTO units(parent_id,type,name) VALUES(?,'university',?)").run(root.id, u).changes;
}
console.log(`${addedUni} دانشگاه افزوده شد (از ${UNIVERSITIES.length}).`);

const counties = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'counties.json'), 'utf8'));
let addedCounty = 0;
for (const [prov, list] of Object.entries(counties)) {
  const uniName = PROV_TO_UNI[prov];
  if (!uniName) { console.warn('دانشگاه برای استان پیدا نشد:', prov); continue; }
  const uni = db.prepare("SELECT id FROM units WHERE parent_id=? AND type='university' AND name=?").get(root.id, uniName);
  if (!uni) { console.warn('دانشگاه در DB نیست:', uniName); continue; }
  for (const c of list) {
    addedCounty += +db.prepare("INSERT OR IGNORE INTO units(parent_id,type,name) VALUES(?,'county',?)").run(uni.id, c).changes;
  }
}
console.log(`${addedCounty} شهرستان افزوده شد.`);
